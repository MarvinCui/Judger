DIMENSIONS = [
    ("color", 'Color', 'One main color', 'More colors', 'Add more colors?'),
    ("bold", 'Boldness', 'More restrained', 'More striking', 'Make it bolder?'),
    ("density", 'Density', 'More breathing room', 'More compact', 'Make it more compact?'),
    ("detail", 'Detail', 'Simpler', 'More layers', 'Add more visual detail?'),
    ("expression", 'Expression', 'More reserved', 'More expressive', 'Make it more expressive?'),
]


def style_css(values: dict) -> str:
    color, bold, density, detail, expression = (values[d[0]] for d in DIMENSIONS)
    # Defaults are neutral. Generic selectors support existing pages; data attributes
    # give an agent precise, non-destructive places to apply additional color.
    delta = color - .5
    saturation = max(0, 1 + delta * 2)
    hue = round(210 + 100 * delta)
    radius = max(0, round(12 + 24 * (detail - .5)))
    gap = round(24 - 24 * (density - .5))
    css = f"""/* Generated by Judger. Adjust with = / -; do not overwrite. */
:root {{
 --trigger-colorfulness: {color:.2f}; --trigger-boldness: {bold:.2f};
 --trigger-density: {density:.2f}; --trigger-detail: {detail:.2f};
 --trigger-expression: {expression:.2f}; --trigger-gap: {gap}px;
 --trigger-radius: {radius}px; --trigger-accent: hsl({hue} 72% 49%);
}}
html {{ filter: saturate({saturation:.2f}); }}
[data-trigger-grid] {{ gap: var(--trigger-gap) !important; }}
[data-trigger-card] {{ border-radius: var(--trigger-radius) !important; }}
"""
    if abs(density - .5) > .001:
        css += f"section, [data-trigger-section] {{ padding-block: {round(56 - 64 * (density - .5))}px !important; }}\n"
        css += f"p, li {{ line-height: {1.65 - .6 * (density - .5):.2f} !important; }}\n"
    if abs(bold - .5) > .001:
        css += f"h1, h2, [data-trigger-title] {{ font-weight: {round(600 + 400 * (bold - .5))} !important; letter-spacing: {-1 - 2 * (bold - .5):.2f}px !important; }}\n"
    if detail < .5:
        css += "[data-trigger-card], .card { box-shadow: none !important; background-image: none !important; }\n"
    elif detail > .5:
        css += f"[data-trigger-card], .card {{ box-shadow: 0 {round(detail*12)}px {round(detail*40)}px #18284d26 !important; border-radius: {radius}px !important; }}\n"
    if color > .5:
        for number, offset in enumerate((0, 100, 220), 1):
            css += f"[data-trigger-card]:nth-child(3n+{number}) {{ background-color: hsl({hue+offset} {round(30+70*color)}% 94%) !important; }}\n"
        css += "[data-trigger-accent], a, button { accent-color: var(--trigger-accent); }\n"
    if abs(expression - .5) > .001:
        css += f"button, [data-trigger-accent] {{ border-radius: {round(8+24*expression)}px !important; letter-spacing: {(expression-.5)*1.2:.2f}px !important; }}\n"
    return css


class Execution:
    def __init__(self, workspace: Path, state: State):
        self.workspace, self.state = workspace.resolve(), state
        self.lock = threading.RLock()
        self.values = {d[0]: .5 for d in DIMENSIONS}
        self.selected = 0
        self.enabled = False
        self.entry = ""
        self.title = 'Live controls'
        self.revision = 0
        self.sent_revision = 0
        self.dirty_at = 0.0
        self.server = None
        self.token = secrets.token_urlsafe(32)
        self.url = ""
        self.meta = self.workspace / ".trigger-agent" / "design.json"
        if self.meta.is_file():
            data = json.loads(self.meta.read_text(encoding="utf-8"))
            for key in self.values:
                if isinstance(data.get(key), (int, float)) and 0 <= data[key] <= 1:
                    self.values[key] = data[key]
        self.initial_values = dict(self.values)
        self.record_revision = state.record_revision
        self.state.execution = self
        self.flusher = threading.Thread(target=self._flush_loop, daemon=True)
        self.flusher.start()

    def safe_file(self, value: str) -> Path:
        path = (self.workspace / value).resolve()
        if not path.is_relative_to(self.workspace) or Workspace.secret_path(path.relative_to(self.workspace)):
            raise ValueError('This file cannot be previewed.')
        return path

    def offer(self, entry: str, title: str = 'Live controls') -> None:
        path = self.safe_file(entry)
        if path.suffix.lower() not in {".html", ".htm"}:
            raise ValueError('This demo previews HTML files.')
        with self.lock:
            self.entry = path.relative_to(self.workspace).as_posix()
            self.title = title[:60]
        self.state.notice = 'Ready to tune the page. Press C for live controls.'

    def discover(self) -> bool:
        with self.lock:
            if self.entry and self.safe_file(self.entry).is_file():
                return True
        paths = sorted(self.workspace.glob("**/index.html"))
        for path in paths:
            try:
                self.offer(path.relative_to(self.workspace).as_posix())
                return True
            except ValueError:
                continue
        return False

    def open(self, browser: bool = True) -> str:
        if not self.entry and not self.discover():
            self.state.notice = 'No webpage to preview yet. Press C after a page is ready.'
            return ""
        self.start_server()
        with self.lock:
            self.enabled = True
            self._save()
        self.state.say(self.url, 'Preview: ')
        self.state.notice = 'Live controls: brackets switch categories, - / = adjust, C returns.'
        if browser:
            threading.Thread(target=self._open_browser, daemon=True).start()
        return self.url

    def _open_browser(self) -> None:
        # Open the preview without taking keyboard focus away from Terminal.
        if sys.platform == "darwin":
            command = ["open", "-g"]
            if Path("/Applications/Google Chrome.app").exists():
                command += ["-a", "Google Chrome"]
            result = subprocess.run(command + [self.url], capture_output=True, timeout=15)
            if result.returncode == 0:
                return
        webbrowser.open(self.url)

    def key(self, key: str, browser: bool = True) -> bool:
        self._sync_history()
        if self.state.mode == "question":
            if key in {"c", "C"}:
                self.state.notice = 'Answer the current main question first, then press C.'
                return True
            return False
        if key in {"c", "C"}:
            if self.enabled:
                self.enabled = False
                self.state.notice = 'Back to questions. Press C to reopen live controls.'
            else:
                self.open(browser=browser)
            return True
        if not self.enabled:
            return False
        with self.lock:
            if key in {"【", "[", "】", "]"}:
                self.selected = (self.selected + (-1 if key in {"【", "["} else 1)) % len(DIMENSIONS)
                return True
            if key in {"=", "-"}:
                dimension = DIMENSIONS[self.selected]
                name = dimension[0]
                old = self.values[name]
                self.values[name] = round(min(1, max(0, old + (.1 if key == "=" else -.1))), 2)
                if old != self.values[name]:
                    self.revision += 1
                    self.dirty_at = time.monotonic()
                    self._save()
                    with self.state.cv:
                        self.state._record("design", dimension[4], key,
                                           f"{dimension[1]}: {round(self.values[name]*100)}%",
                                           self.entry, {"dimension": name})
                    self.state.log("design_key", dimension=name, key=key, values=dict(self.values))
                self.state.notice = f"{dimension[1]}: {round(self.values[name]*100)}% · {dimension[3] if key == '=' else dimension[2]}"
                return True
            if key == "0":
                sent = self.flush()
                if self.state.pending:
                    self.state.send_pending()
                else:
                    self.state.notice = 'Changes sent.' if sent else 'These changes have already been sent.'
                return True
        return False

    def undo(self) -> None:
        with self.state.cv:
            record = next((r for r in reversed(self.state.records)
                           if r["kind"] == "design" and r["status"] != "withdrawn"), None)
        if record:
            self.state.revise_record(record["id"], None)
            self._sync_history()
        else:
            self.state.notice = 'No page adjustments to undo yet.'

    def _sync_history(self) -> None:
        with self.state.cv:
            version = self.state.record_revision
            if version == self.record_revision:
                return
            choices = [(r["detail"]["dimension"], r["key"]) for r in self.state.records
                       if r["kind"] == "design" and r["status"] != "withdrawn"]
        with self.lock:
            self.record_revision = version
            values = dict(self.initial_values)
            for name, key in choices:
                values[name] = round(min(1, max(0, values[name] + (.1 if key == "=" else -.1))), 2)
            if values != self.values:
                self.values = values
                self.revision += 1
                self.dirty_at = time.monotonic()
                self._save()

    def _save(self) -> None:
        self.meta.parent.mkdir(parents=True, exist_ok=True)
        temp = self.meta.with_suffix(".tmp")
        temp.write_text(json.dumps(self.values, ensure_ascii=False, indent=2), encoding="utf-8")
        temp.replace(self.meta)
        css = self.workspace / "trigger-style.css"
        temp_css = css.with_suffix(".css.tmp")
        temp_css.write_text(style_css(self.values), encoding="utf-8")
        temp_css.replace(css)
        # Keep exported static pages live too. Agents need not remember to add the link.
        entry = self.safe_file(self.entry)
        if entry.is_file():
            page = entry.read_text(encoding="utf-8")
            if "data-trigger-styles" not in page:
                import os
                relative = Path(os.path.relpath(css, entry.parent)).as_posix()
                link = f'<link data-trigger-styles rel="stylesheet" href="{html.escape(relative, quote=True)}">'
                page = page.replace("</head>", link + "</head>", 1) if "</head>" in page else link + page
                backup = self.meta.parent / "backups" / f"preview-{time.time_ns()}.html"
                backup.parent.mkdir(exist_ok=True)
                backup.write_text(entry.read_text(encoding="utf-8"), encoding="utf-8")
                entry.write_text(page, encoding="utf-8")

    def spec(self) -> dict:
        with self.lock:
            return {"entry": self.entry, "values": dict(self.values), "stylesheet": "trigger-style.css",
                    "meaning": {d[0]: {"0": d[2], "1": d[3]} for d in DIMENSIONS}}

    def flush(self) -> bool:
        with self.lock:
            if self.sent_revision == self.revision:
                return False
            payload = self.spec()
            self.sent_revision = self.revision
        with self.state.cv:
            self.state._enqueue("design", {"design": payload,
                "text": 'Apply these latest settings to the real webpage. The user controls trigger-style.css; do not overwrite it.'})
        self.state.log("design_commit", design=payload)
        return True

    def _flush_loop(self) -> None:
        while not self.state.stopped.wait(.15):
            self._sync_history()
            with self.lock:
                ready = self.revision != self.sent_revision and time.monotonic() - self.dirty_at >= .7
            if ready:
                self.flush()

    def snapshot(self) -> dict:
        self._sync_history()
        view = self.state.snapshot()
        with self.lock:
            path = self.safe_file(self.entry) if self.entry else None
            if path and path.is_file():
                try:
                    stamp = hashlib.sha256(path.read_bytes()).hexdigest()[:14]
                except OSError:
                    stamp = ""
            else:
                stamp = ""
            return {"title": self.title, "enabled": self.enabled and view.mode != "question", "selected": self.selected,
                    "values": dict(self.values), "dimensions": DIMENSIONS, "entry": self.entry,
                    "stamp": stamp, "css": style_css(self.values), "revision": self.revision,
                    "mode": view.mode, "question": (view.question or {}).get("question") if view.mode == "question" else
                    (view.node.question if view.node else 'One moment. Next question coming up.'),
                    "notice": view.notice, "status": self.state.executor_status,
                    "lines": view.lines[-16:], "records": [
                        {k: r[k] for k in ("id", "kind", "question", "key", "status")} for r in view.records]}

    def start_server(self) -> None:
        with self.lock:
            if self.server:
                return
            controller = self

            class Handler(BaseHTTPRequestHandler):
                def log_message(self, *args):
                    pass

                def respond(self, data: bytes, content_type: str, status: int = 200):
                    self.send_response(status)
                    self.send_header("Content-Type", content_type)
                    self.send_header("Cache-Control", "no-store")
                    self.send_header("X-Content-Type-Options", "nosniff")
                    self.send_header("Referrer-Policy", "no-referrer")
                    self.send_header("Content-Length", str(len(data)))
                    self.end_headers()
                    try:
                        self.wfile.write(data)
                    except (BrokenPipeError, ConnectionResetError):
                        pass

                def host_ok(self):
                    return self.headers.get("Host") == f"127.0.0.1:{controller.server.server_port}"

                def authorized(self):
                    origin = self.headers.get("Origin")
                    expected = f"http://127.0.0.1:{controller.server.server_port}"
                    return (self.host_ok() and origin in {None, expected}
                            and secrets.compare_digest(self.headers.get("X-Trigger-Token", ""), controller.token))

                def do_GET(self):
                    route = urlsplit(self.path).path
                    if not self.host_ok():
                        return self.respond(b"Forbidden", "text/plain", 403)
                    if route == "/":
                        self.send_response(302)
                        self.send_header("Location", "/project/" + quote(controller.entry, safe="/"))
                        self.end_headers()
                        return
                    if route == "/_trigger/version":
                        if not self.authorized():
                            return self.respond(b"Forbidden", "text/plain", 403)
                        data = controller.snapshot()
                        # The browser only receives preview data. Questions, answers,
                        # task controls and model output never leave Terminal.
                        payload = {k: data[k] for k in ("stamp", "css", "entry")}
                        return self.respond(json.dumps(payload, ensure_ascii=False).encode(), "application/json")
                    if route.startswith("/project/"):
                        try:
                            path = controller.safe_file(unquote(route[len("/project/"):]))
                            allowed = {".html", ".htm", ".css", ".js", ".mjs", ".json", ".svg", ".png", ".jpg", ".jpeg", ".gif", ".webp", ".ico", ".woff", ".woff2", ".ttf", ".mp4", ".webm"}
                            if path.suffix.lower() not in allowed or not path.is_file() or path.stat().st_size > 20_000_000:
                                raise ValueError("Unavailable")
                            data = path.read_bytes()
                            if path.suffix.lower() in {".html", ".htm"}:
                                data += controller.reload_script().encode()
                            return self.respond(data, (mimetypes.guess_type(path.name)[0] or "application/octet-stream") + "; charset=utf-8")
                        except (ValueError, OSError):
                            pass
                    self.respond(b"Not found", "text/plain", 404)

                def do_POST(self):
                    # There is deliberately no browser control API.
                    self.respond(b"Not found", "text/plain", 404)

            self.server = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
            self.server.daemon_threads = True
            self.url = f"http://127.0.0.1:{self.server.server_port}/project/" + quote(self.entry, safe="/")
            threading.Thread(target=self.server.serve_forever, daemon=True).start()

    def reload_script(self) -> str:
        data = self.snapshot()
        settings = json.dumps({"token": self.token, "stamp": data["stamp"]})
        return """<script data-trigger-preview>(()=>{
const config=SETTINGS;let stamp=config.stamp,busy=false;
async function refresh(){if(busy)return;busy=true;try{
const r=await fetch('/_trigger/version',{headers:{'X-Trigger-Token':config.token},cache:'no-store'});if(!r.ok)return;
const d=await r.json();if(stamp&&d.stamp&&stamp!==d.stamp){location.reload();return}stamp=d.stamp;
let style=document.getElementById('trigger-preview-style');if(!style){style=document.createElement('style');style.id='trigger-preview-style';document.head.append(style)}style.textContent=d.css;
}catch{}finally{busy=false}}refresh();setInterval(refresh,200);
})();</script>""".replace("SETTINGS", settings)

    def close(self) -> None:
        self.flush()
        if self.server:
            self.server.shutdown()
            self.server.server_close()
        self.flusher.join(timeout=1)
